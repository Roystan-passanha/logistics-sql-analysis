"""Load the CSVs into SQLite, run every query in sql/, and write results and charts.

Usage:
    python generate_data.py      # once, creates data/*.csv
    python run_analysis.py       # creates delivery.db, docs/results.md, docs/*.png
"""
import csv
import sqlite3
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

ROOT = Path(__file__).resolve().parent
SQL = ROOT / "sql"
DATA = ROOT / "data"
DOCS = ROOT / "docs"


def build_db(path: Path) -> sqlite3.Connection:
    path.unlink(missing_ok=True)
    con = sqlite3.connect(path)
    con.executescript((SQL / "01_schema.sql").read_text())
    for table in ("warehouses", "customers", "deliveries"):
        with (DATA / f"{table}.csv").open() as f:
            reader = csv.reader(f)
            headers = next(reader)
            rows = [[v if v != "" else None for v in row] for row in reader]
        marks = ",".join("?" * len(headers))
        con.executemany(f"INSERT INTO {table} ({','.join(headers)}) VALUES ({marks})", rows)
    con.commit()
    return con


def run(con: sqlite3.Connection, name: str) -> tuple[list[str], list[tuple]]:
    cur = con.execute((SQL / name).read_text())
    return [d[0] for d in cur.description], cur.fetchall()


def to_markdown(cols, rows) -> str:
    lines = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    lines += ["| " + " | ".join("" if v is None else str(v) for v in r) + " |" for r in rows]
    return "\n".join(lines)


def charts(con: sqlite3.Connection) -> None:
    plt.rcParams.update({"font.size": 10, "axes.spines.top": False, "axes.spines.right": False})

    cols, rows = run(con, "04_monthly_trend.sql")
    months = [r[0][5:] for r in rows]
    fig, ax1 = plt.subplots(figsize=(8, 3.6))
    ax1.bar(months, [r[1] for r in rows], color="#c9d6ea", label="Pallets")
    ax1.set_ylabel("Pallets delivered")
    ax2 = ax1.twinx()
    ax2.plot(months, [r[2] for r in rows], color="#1f4e8c", marker="o", label="On-time %")
    ax2.set_ylabel("On-time %")
    ax2.set_ylim(60, 100)
    ax2.spines["top"].set_visible(False)
    ax1.set_title("2025 volume and on-time rate by month")
    fig.tight_layout()
    fig.savefig(DOCS / "monthly_trend.png", dpi=160)
    plt.close(fig)

    cols, rows = run(con, "03_on_time_by_region.sql")
    rows = sorted(rows, key=lambda r: r[3])
    fig, ax = plt.subplots(figsize=(6, 2.8))
    colors = ["#c0392b" if r[3] == rows[0][3] else "#1f4e8c" for r in rows]
    ax.barh([r[0] for r in rows], [r[3] for r in rows], color=colors)
    for i, r in enumerate(rows):
        ax.text(r[3] + 0.5, i, f"{r[3]}%", va="center")
    ax.set_xlim(60, 100)
    ax.set_xlabel("On-time %")
    ax.set_title("On-time delivery by region")
    fig.tight_layout()
    fig.savefig(DOCS / "on_time_by_region.png", dpi=160)
    plt.close(fig)


def main() -> None:
    DOCS.mkdir(exist_ok=True)
    con = build_db(ROOT / "delivery.db")
    parts = ["# Query results\n", "Generated by `run_analysis.py` from synthetic data.\n"]
    for file in sorted(SQL.glob("0*.sql"))[1:]:
        cols, rows = run(con, file.name)
        title = file.read_text().splitlines()[0].lstrip("- ").strip()
        parts.append(f"## {file.name}\n\n{title}\n\n{to_markdown(cols, rows)}\n")
    (DOCS / "results.md").write_text("\n".join(parts))
    charts(con)
    print("Wrote docs/results.md and charts")


if __name__ == "__main__":
    main()
